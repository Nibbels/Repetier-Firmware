"""Execute the actual Timer1 remainder asm with a small instruction-level model.

The model covers only the listed instructions, not AVR peripherals or IRQ
latency. Fail on unknown instructions. Compare all final 16-bit remainders,
different interrupted registers, and seeded 24-bit chunk cases.
"""
import ast
import random
import re
from pathlib import Path

source = (Path(__file__).resolve().parents[1] / "Repetier" / "HAL.cpp").read_text()
block = source.split("ISR(TIMER1_COMPA_vect) {", 1)[1].split("if (doExit)", 1)[0]
assembly = "".join(ast.literal_eval(s) for s in re.findall(r'(?m)^\s*("(?:\\.|[^"\\])*")', block))
instructions = []
labels = {}
for line in assembly.splitlines():
    line = line.strip()
    if not line:
        continue
    if ":" in line:
        label, line = line.split(":", 1)
        labels[label] = len(instructions)
        line = line.strip()
    if line:
        op, _, args = line.partition(" ")
        instructions.append((op, [a.strip() for a in args.split(",")]))

def execute(wait, r22, r23, ex):
    regs = {"r1": 0, "r22": r22, "r23": r23, "%[ex]": ex}
    mem = {"stepperWait": wait & 255, "stepperWait+1": (wait >> 8) & 255,
           "stepperWait+2": wait >> 16, "%[ocr]": 0x00, "%[ocr]+1": 0x80}
    z = False
    carry = 0
    pc = 0
    while pc < len(instructions):
        op, args = instructions[pc]
        pc += 1
        if op == "lds":
            regs[args[0]] = mem[args[1]]
        elif op == "sts":
            mem[args[0]] = regs[args[1]]
        elif op == "ldi":
            regs[args[0]] = int(args[1], 0)
        elif op == "tst":
            z = regs[args[0]] == 0
        elif op == "mov":
            regs[args[0]] = regs[args[1]]
        elif op == "or":
            regs[args[0]] |= regs[args[1]]
            z = regs[args[0]] == 0
        elif op in ("subi", "sbci"):
            value = regs[args[0]] - int(args[1], 0) - (carry if op == "sbci" else 0)
            carry = int(value < 0)
            regs[args[0]] = value & 255
            z = regs[args[0]] == 0 and (z if op == "sbci" else True)
        elif op in ("brne", "breq", "rjmp"):
            if op == "rjmp" or (op == "brne" and not z) or (op == "breq" and z):
                pc = labels[args[0]]
        else:
            raise AssertionError("Unexpected instruction: " + op)
    remaining = mem["stepperWait"] | mem["stepperWait+1"] << 8 | mem["stepperWait+2"] << 16
    compare = mem["%[ocr]"] | mem["%[ocr]+1"] << 8
    return bool(regs["%[ex]"]), remaining, compare

def reference(wait):
    if wait == 0:
        return False, 0, 32768
    if wait < 65536:
        return True, 0, wait
    return True, wait - 32768, 32768

rng = random.Random(0x0027)
count = 0
for wait in range(65536):
    for initial in (0, 255, rng.randrange(256)):
        result = execute(wait, initial, rng.randrange(256), rng.randrange(256))
        assert result == reference(wait), (hex(wait), initial, result, reference(wait))
        count += 1
for wait in [65536, 65537, 0x17fff, 0x18000, 0xffffff] + [rng.randrange(65536, 1 << 24) for _ in range(10000)]:
    assert execute(wait, 255, 255, 255) == reference(wait), hex(wait)
    count += 1

# Reachable chain generated by setTimer's split at 65280 ticks:
# all subsequent chunks leave >=32512 ticks, never a short final compare.
for delay in (65279, 65280, 65535, 65536, 0x11abc, 0x18000, 1600000, 0x3fffff, 0xffffff):
    if delay < 65280:
        continue
    wait = delay - 32768
    total = 32768
    while wait:
        assert wait >= 32512
        exited, wait, compare = execute(wait, 0x55, 0xaa, 0xfe)
        assert exited
        total += compare
    assert total == delay, (delay, total)
print(f"Timer1 remainder: {count} instruction-model cases and split chains passed")
